#!/usr/bin/env python3
"""Compare randomized provider-visible message bytes with master 24ebef59.

The baseline commit represents behavior before the signed-thinking hold changes.
The two conversation shapes omit all thinking or keep it only in completed turns.
Run only in a disposable runner checkout. BASE_SRC holds the production files
listed in base-files.txt, extracted with git show from master 24ebef59. Driver
copies are generated beside the originals so their relative imports stay valid.
The originals and all production files are restored even when a test fails.
"""
import hashlib
import json
import os
from pathlib import Path
import subprocess
import sys

if os.environ.get("MC_665_R3") != "1":
    print("skipped: set MC_665_R3=1 to run the review differential")
    sys.exit(0)
if os.environ.get("MC_665_R3_SCRATCH") != "1":
    sys.exit("refusing: set MC_665_R3_SCRATCH=1 only in a disposable checkout")

root = Path.cwd()
base = Path(os.environ["BASE_SRC"]).resolve()
out = Path(os.environ["R3_OUT"]).resolve()
out.mkdir(parents=True, exist_ok=True)
paths = (base / "base-files.txt").read_text().splitlines()
saved = {p: (root / p).read_bytes() for p in paths}
seeds = [int(s) for s in os.environ.get("R3_SEEDS", "665,664,650,1,2,3,7,8").split(",")]
passes = int(os.environ.get("R3_PASSES", "320"))
originals = {
    "oc": root / "packages/plugin/src/hooks/magic-context/issue-665-hold-review-r2.test.ts",
    "pi": root / "packages/pi-plugin/src/issue-665-hold-review-r2.test.ts",
}
generated = {h: p.with_name("_issue-665-hold-review-r3-generated.test.ts") for h, p in originals.items()}
if any(p.exists() for p in generated.values()):
    sys.exit("refusing to overwrite an existing generated driver")


def driver(host, no_signed):
    source = originals[host].read_text().split("const SEEDS =", 1)[0]
    if no_signed:
        # Completed-turn signed thinking is the only thinking generated by
        # the original unheld-bound conversation. Remove the final answer's
        # thinking block as well, so this variant contains no signed blocks.
        before = source
        source = source.replace("[reasoning(), { type: \"text\", text: `final ${clock}` }]", "[{ type: \"text\", text: `final ${clock}` }]")
        source = source.replace("\n\t\t\t\t\t\tthinking(),", "")
        if source == before:
            raise RuntimeError(f"no-signed driver edit did not apply: {host}")
    source = source.replace("JSON.stringify(record)", "JSON.stringify({...record, wire: served?.map(providerKey), signedCount: served ? signedPrefixes(served).size : 0})")
    loop = []
    for seed in seeds:
        for lane in (["opencode1", "opencode2"] if host == "oc" else ["pi"]):
            options = f'scenario: "unheld-bound", seed: {seed}, passes: {passes}, trace: `${{process.env.R3_TRACE}}.{lane}-{seed}.jsonl`'
            if host == "oc":
                options += f', host: "{lane}"'
            loop.append(f'''{"it" if host == "oc" else "test"}.skipIf(process.env.MC_665_R3 !== "1")("r3 {lane} seed {seed}", async () => {{
    const result = await {"runOpenCodeHoldDriver" if host == "oc" else "runPiHoldDriver"}({{{options}}});
    expect(result.records).toHaveLength({passes});
    expect(result.violations.filter(v => v.kind === "refusal")).toEqual([]);
}}, 600_000);''')
    return source + "\n" + "\n".join(loop) + "\n"


results = []
try:
    print(subprocess.check_output(["bun", "--version"], text=True).strip(), flush=True)
    for shape in ["no-signed", "no-kept"]:
        for host, path in generated.items():
            path.write_text(driver(host, shape == "no-signed"))
        for arm in ["head", "master"]:
            for p, data in saved.items():
                (root / p).write_bytes(data if arm == "head" else (base / p).read_bytes())
            folder = out / shape / arm
            folder.mkdir(parents=True, exist_ok=True)
            for host, path in generated.items():
                env = dict(os.environ, R3_TRACE=str(folder / "trace"))
                log = folder / f"{host}.log"
                with log.open("w") as f:
                    result = subprocess.run(["bun", "test", str(path)], env=env, stdout=f, stderr=subprocess.STDOUT)
                print(f"{shape}/{arm}/{host}: exit={result.returncode}, log={log}", flush=True)
                if result.returncode:
                    print(log.read_text()[-8000:], flush=True)
                    raise RuntimeError("driver failed; no parity result is inferred")
        traces = sorted((out / shape / "head").glob("trace.*.jsonl"))
        if len(traces) != len(seeds) * 3:
            raise RuntimeError("missing host/seed traces; no parity result is inferred")
        for trace in traces:
            head = [json.loads(l) for l in trace.read_text().splitlines()]
            master_path = out / shape / "master" / trace.name
            master = [json.loads(l) for l in master_path.read_text().splitlines()]
            if len(head) != passes or len(master) != passes:
                raise RuntimeError("incomplete trace")
            if shape == "no-signed" and any(r["signedCount"] for r in head + master):
                raise RuntimeError("no-signed fixture served signed blocks")
            differences = []
            previous_differed = False
            for h, m in zip(head, master):
                fields = [f for f in ["hash", "pending", "pair", "tags", "refused"] if h[f] != m[f]]
                differed = "hash" in fields
                if differed and not previous_differed:
                    a, b = h.get("wire", []), m.get("wire", [])
                    first = next((i for i in range(max(len(a), len(b))) if (a[i] if i < len(a) else "") != (b[i] if i < len(b) else "")), -1)
                    av, bv = (a[first] if 0 <= first < len(a) else ""), (b[first] if 0 <= first < len(b) else "")
                    at = next((i for i in range(min(len(av), len(bv))) if av[i] != bv[i]), min(len(av), len(bv)))
                    print(json.dumps({"shape": shape, "trace": trace.name, "root": h["pass"], "events": h["events"], "fields": fields, "pending": [h["pending"], m["pending"]], "first_message": first, "at": at, "head": av[max(0, at-80):at+160], "master": bv[max(0, at-80):at+160]}), flush=True)
                previous_differed = differed
                if fields:
                    differences.append({"pass": h["pass"], "events": h["events"], "fields": fields, "head": {k: v for k, v in h.items() if k != "wire"}, "master": {k: v for k, v in m.items() if k != "wire"}})
            results.append({"shape": shape, "trace": trace.name, "passes": passes, "served_differences": sum("hash" in d["fields"] for d in differences), "differences": differences})
    summary = {"master": "24ebef59e11a61a0317aafe53ce16c73451b7439", "seeds": seeds, "passes_per_sequence": passes, "total_passes": sum(r["passes"] for r in results), "served_differences": sum(r["served_differences"] for r in results), "sequences": results, "baseline_file_sha256": {p: hashlib.sha256((base / p).read_bytes()).hexdigest() for p in paths}}
    (out / "summary.json").write_text(json.dumps(summary, indent=2) + "\n")
    print(json.dumps({k: v for k, v in summary.items() if k not in ["sequences", "baseline_file_sha256"]}), flush=True)
    for shape in ["no-signed", "no-kept"]:
        for arm in ["head", "master"]:
            for host in ["oc", "pi"]:
                print(f"{shape}/{arm}/{host} test summary:\n{(out / shape / arm / (host + '.log')).read_text()[-250:]}", flush=True)
    for r in results:
        print(f'{r["shape"]} {r["trace"]}: {r["served_differences"]} served differences; {len(r["differences"])} state differences', flush=True)
finally:
    for p, data in saved.items():
        (root / p).write_bytes(data)
    for p in generated.values():
        p.unlink(missing_ok=True)

if summary["served_differences"]:
    sys.exit(1)
